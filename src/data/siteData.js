export function optimizeCloudinary(url, params = 'q_auto,f_auto') {
  if (!url || !url.includes('res.cloudinary.com')) return url;
  if (url.includes('/video/upload/')) {
    return url.replace('/video/upload/', `/video/upload/${params}/`);
  }
  return url.replace('/image/upload/', `/image/upload/${params}/`);
}

export function getVideoPoster(videoUrl) {
  if (!videoUrl || !videoUrl.includes('res.cloudinary.com')) return undefined;
  return videoUrl.replace(/\.\w+$/, '.jpg').replace('/video/upload/', '/video/upload/w_600,q_auto,f_auto/so_1/');
}
